import '../errors/engine_error.dart';
import '../ids/identifiers.dart';
import '../result/engine_result.dart';

final class PacketMarkerPayload {
  PacketMarkerPayload({
    required this.packetId,
    required this.pageIndex,
    required Iterable<int> markerIds,
  }) : markerIds = List.unmodifiable(markerIds);

  final PacketId packetId;
  final int pageIndex;
  final List<int> markerIds;
}

/// Deterministic packet/page encoding for the repository's DICT_4X4_50.
///
/// IDs 0-9 are packet identity digits. Registration IDs remain in 10-49.
/// Four ordered header slots encode `packetSequence * 10 + pageIndex`.
final class PacketMarkerCodec {
  const PacketMarkerCodec();

  static const codecVersion = 1;
  static const markerCount = 4;
  static const minimumIdentityMarkerId = 0;
  static const maximumIdentityMarkerId = 9;
  static const maximumPacketSequence = 999;
  static const maximumPageIndex = 9;

  bool isIdentityMarkerId(int markerId) =>
      markerId >= minimumIdentityMarkerId &&
      markerId <= maximumIdentityMarkerId;

  EngineResult<PacketMarkerPayload> encode({
    required PacketId packetId,
    required int pageIndex,
  }) {
    if (pageIndex < 0 || pageIndex > maximumPageIndex) {
      return _failure(
        'PACKET_MARKER_CAPACITY_EXCEEDED',
        'Packet page index exceeds the marker codec capacity.',
        {'pageIndex': pageIndex, 'maximumPageIndex': maximumPageIndex},
      );
    }
    int sequence;
    try {
      sequence = packetId.sequence;
    } on Object catch (error) {
      return _failure(
        'PACKET_ID_INVALID',
        'PacketId was not generated by the packet identity codec.',
        {'packetId': packetId.value, 'cause': error.toString()},
      );
    }
    if (sequence > maximumPacketSequence) {
      return _failure(
        'PACKET_MARKER_CAPACITY_EXCEEDED',
        'Packet sequence exceeds the marker codec capacity.',
      );
    }
    final code = sequence * 10 + pageIndex;
    final digits = code.toString().padLeft(markerCount, '0');
    return EngineResult.success(
      PacketMarkerPayload(
        packetId: packetId,
        pageIndex: pageIndex,
        markerIds: List.unmodifiable(
          digits.codeUnits.map((value) => value - 48),
        ),
      ),
    );
  }

  EngineResult<PacketMarkerPayload> decode(
    Iterable<int> orderedMarkerIds, {
    int version = PacketMarkerCodec.codecVersion,
  }) {
    if (version != codecVersion) {
      return _failure(
        'PACKET_CODEC_VERSION_UNSUPPORTED',
        'Packet marker codec version is not supported.',
        {'version': version, 'supportedVersion': codecVersion},
      );
    }
    final ids = orderedMarkerIds.toList(growable: false);
    if (ids.length != markerCount) {
      return _failure(
        'PACKET_IDENTITY_MARKER_COUNT_INVALID',
        'Packet identity requires exactly $markerCount ordered markers.',
        {'detectedCount': ids.length, 'requiredCount': markerCount},
      );
    }
    if (ids.any((id) => !isIdentityMarkerId(id))) {
      return _failure(
        'PACKET_IDENTITY_MARKER_INVALID',
        'Packet identity contains a marker outside the reserved range.',
        {'markerIds': ids},
      );
    }
    final code = ids.fold<int>(0, (value, digit) => value * 10 + digit);
    final sequence = code ~/ 10;
    final pageIndex = code % 10;
    final packetId = PacketId.fromSequence(sequence);
    return EngineResult.success(
      PacketMarkerPayload(
        packetId: packetId,
        pageIndex: pageIndex,
        markerIds: List.unmodifiable(ids),
      ),
    );
  }

  EngineResult<PacketMarkerPayload> _failure(
    String code,
    String message, [
    Map<String, Object?> details = const {},
  ]) => EngineResult.failure(
    EngineError(code: code, message: message, details: details),
  );
}
